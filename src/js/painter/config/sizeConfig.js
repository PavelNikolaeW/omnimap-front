/**
 * Block Size Configuration
 *
 * Конфигурация для определения размерных классов блоков на основе
 * соотношения площади блока к площади экрана.
 */

/**
 * Пороги размеров (соотношение площади блока к площади экрана)
 *
 * Паттерн: каждый следующий порог примерно в 2 раза меньше предыдущего,
 * создавая экспоненциальную шкалу размеров.
 *
 * Пример: на экране 1920x1080 (2073600 px):
 * - xxl: > 932820 px (блок ~966x966)
 * - xl:  > 466410 px (блок ~683x683)
 * - l:   > 233280 px (блок ~483x483)
 * - m:   > 122342 px (блок ~350x350)
 * - s:   > 49766 px  (блок ~223x223)
 * - xs:  > 24883 px  (блок ~158x158)
 * - xxs: > 2074 px   (блок ~46x46)
 * - xxxs: <= 2074 px
 */
export const SIZE_THRESHOLDS = {
    xxl:  0.45,    // > 45% экрана
    xl:   0.225,   // > 22.5% (половина xxl)
    l:    0.1125,  // > 11.25% (половина xl)
    m:    0.059,   // > 5.9%
    s:    0.024,   // > 2.4%
    xs:   0.012,   // > 1.2%
    xxs:  0.001,   // > 0.1%
    // xxxs: всё что меньше
};

/**
 * Границы aspect ratio для определения формы блока
 *
 * Aspect ratio = width / height
 * - < SQUARE_MIN (0.7) → высокий (tall)
 * - SQUARE_MIN до SQUARE_MAX → квадратный
 * - > SQUARE_MAX (1.49) → широкий (wide)
 *
 * Примечание: границы немного асимметричны относительно 1.0,
 * чтобы блоки близкие к квадрату считались квадратными.
 */
export const ASPECT_RATIO = {
    SQUARE_MIN: 0.7,   // ниже - высокий
    SQUARE_MAX: 1.49,  // выше - широкий
};

/**
 * Суффиксы формы для layout строки
 */
export const SHAPES = {
    SQUARE: 'sq',  // квадратный (0.7 <= ratio <= 1.49)
    WIDE: 'w',     // широкий (ratio > 1.49)
    TALL: 'h',     // высокий (ratio < 0.7)
};

/**
 * Порядок размеров от большего к меньшему
 * Используется для итерации и сравнения размеров
 */
export const SIZE_ORDER = ['xxl', 'xl', 'l', 'm', 's', 'xs', 'xxs', 'xxxs'];

/**
 * Минимальный размер блока для рендеринга контента (в пикселях)
 * Блоки меньше этого размера не рендерят дочерние элементы
 */
export const MIN_RENDER_SIZE = 40;

/**
 * Максимальная глубина рендеринга дерева блоков
 */
export const MAX_RENDER_DEPTH = 40;
